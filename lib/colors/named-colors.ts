// -----------------------------------------------------------------------------
// @file: lib/colors/named-colors.ts
// @purpose: Colors with their own indexed page at /colors/hex/[hex]: the CSS named
//           colors people look up, plus common design color names. Other HEX values
//           still get a working page, but it stays out of search results, so the
//           site doesn't publish millions of near-identical pages.
// -----------------------------------------------------------------------------

export interface NamedColor {
  name: string;
  hex: string;
}

function named(entries: [string, string][]): NamedColor[] {
  return entries.map(([name, hex]) => ({ name, hex }));
}

